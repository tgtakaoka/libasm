#define ONAL(name, opr, at, ...) ERRT(name, opr, OPERAND_NOT_ALIGNED, at, __VA_ARGS__)

DisI8096 dis8096;
Disassembler &disassembler(dis8096);

bool is8096() {
    return strcasecmp_P("8096", dis8096.cpu_P()) == 0;
}

bool is80196kb() {
    return strcasecmp_P("80196KB", dis8096.cpu_P()) == 0;
}

bool is80196() {
    return strcasecmp_P("80196", dis8096.cpu_P()) == 0;
}

bool is80196n() {
    return strcasecmp_P("80196N", dis8096.cpu_P()) == 0;
}

bool is80296() {
    return strcasecmp_P("80296", dis8096.cpu_P()) == 0;
}

// The KB additions are on every CPU but the 8096; the KC additions are on the
// KC and later; the 1-Mbyte instructions are on the N and the 296.
bool hasKb() {
    return !is8096();
}

bool hasKc() {
    return is80196() || is80196n() || is80296();
}

bool hasN() {
    return is80196n() || is80296();
}

// Only the 80196 and the N have a peripheral transaction server.
bool hasPts() {
    return is80196() || is80196n();
}

void set_up() {
    disassembler.reset();
}

void tear_down() {
    symtab.reset();
}

