AsmMc68HC12 asm6812;
Assembler &assembler(asm6812);

bool m68hcs12x() {
    return strcmp("68HCS12X", assembler.config().cpu_P()) == 0;
}

bool m68hc12() {
    return strcmp("68HC12", assembler.config().cpu_P()) == 0;
}

void set_up() {
    assembler.reset();
}

void tear_down() {
    symtab.reset();
}

// clang-format off
