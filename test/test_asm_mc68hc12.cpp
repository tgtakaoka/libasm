    EQUALS_P("cpu 68hc12", "68HC12", assembler.config().cpu_P());

    EQUALS("cpu MC68HC12", true, assembler.setCpu("MC68HC12"));
    EQUALS_P("cpu MC68HC12", "68HC12", assembler.config().cpu_P());

